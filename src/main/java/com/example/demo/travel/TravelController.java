package com.example.demo.travel;

import static com.example.demo.travel.TravelModels.*;

import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestHeader;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

/** Public API used by a WeChat Mini Program, customer service console, or the iLink command adapter. */
@RestController
@RequestMapping("/api/travel")
public class TravelController {
	private final TravelPlanService plans;
	private final TravelIntegrationGateway integrations;
	private final TravelOrderService orders;
	private final IdempotencyService idempotency;
	private final TravelAuditService audit;
	private final TravelPrincipalService principals;

	public TravelController(TravelPlanService plans, TravelIntegrationGateway integrations,
			TravelOrderService orders, IdempotencyService idempotency, TravelAuditService audit, TravelPrincipalService principals) {
		this.plans = plans;
		this.integrations = integrations;
		this.orders = orders;
		this.idempotency = idempotency;
		this.audit = audit;
		this.principals = principals;
	}

	@PostMapping("/plans")
	public PlanResponse createPlan(@RequestHeader("Authorization") String authorization, @RequestBody PlanRequest request) {
		String userId = principals.requireSubject(authorization);
		PlanResponse response = plans.createPlan(new PlanRequest(userId, request.destination(), request.departureDate(), request.days(), request.travelers(), request.budgetCents(), request.interests()));
		audit.record("PLAN_CREATED", userId, null, response.planId());
		return response;
	}

	@GetMapping("/plans/{planId}")
	public PlanResponse getPlan(@PathVariable String planId, @RequestHeader("Authorization") String authorization) { return plans.getPlan(planId, principals.requireSubject(authorization)); }

	@PostMapping("/ticket-quotes")
	public TicketQuote quote(@RequestHeader("Authorization") String authorization, @RequestBody TicketQuoteRequest request) {
		plans.getPlan(request.planId(), principals.requireSubject(authorization)); // A quote must be based on a plan generated by this service.
		return integrations.quote(request.attractionId());
	}

	@PostMapping("/orders")
	public OrderResponse confirm(@RequestHeader("Authorization") String authorization, @RequestHeader(value = "Idempotency-Key", required = false) String key,
			@RequestBody ConfirmOrderRequest request) {
		String userId = principals.requireSubject(authorization);
		request = new ConfirmOrderRequest(userId, request.planId(), request.optionId(), request.quoteId(), request.ticketOfferIds(), request.identityVerificationToken());
		String fingerprint = request.planId() + "|" + request.optionId() + "|" + request.quoteId() + "|" + request.ticketOfferIds();
		ConfirmOrderRequest protectedRequest = request;
		return idempotency.execute("order-create", userId, key, fingerprint, () -> orders.confirm(protectedRequest));
	}

	@PostMapping("/external-checkouts")
	public OrderResponse createExternalCheckout(
			@RequestHeader("Authorization") String authorization,
			@RequestHeader(value = "Idempotency-Key", required = false) String key,
			@RequestBody ExternalCheckoutRequest request) {
		String userId = principals.requireSubject(authorization);
		request = new ExternalCheckoutRequest(userId, request.planId(), request.optionId(),
				request.attractionId(), request.attractionName(), request.visitDate(),
				request.provider(), request.providerProductId(), request.providerSkuId(),
				request.productName(), request.ticketType(),
				request.quantity(), request.unitPriceCents(), request.expectedAmountCents(),
				request.bundle(), request.bundleContents(), request.refundRule(),
				request.selectionReason(), request.checkoutUrl(), request.sourceCheckedAt());
		String fingerprint = request.planId() + "|" + request.optionId() + "|"
				+ request.attractionId() + "|" + request.visitDate() + "|"
				+ request.provider() + "|" + request.productName() + "|"
				+ request.ticketType() + "|" + request.quantity() + "|"
				+ request.checkoutUrl();
		ExternalCheckoutRequest protectedRequest = request;
		return idempotency.execute("external-checkout-create", userId, key, fingerprint,
				() -> orders.createExternalCheckout(protectedRequest));
	}

	@GetMapping("/orders/{orderId}")
	public OrderResponse getOrder(@PathVariable String orderId, @RequestHeader("Authorization") String authorization) {
		return orders.get(orderId, principals.requireSubject(authorization));
	}

	@PostMapping("/orders/{orderId}/external-purchase")
	public OrderResponse recordExternalPurchase(@PathVariable String orderId,
			@RequestHeader("Authorization") String authorization,
			@RequestHeader(value = "Idempotency-Key", required = false) String key,
			@RequestBody ExternalPurchaseRecordRequest request) {
		String userId = principals.requireSubject(authorization);
		request = new ExternalPurchaseRecordRequest(userId, request.providerOrderId(),
				request.actualAmountCents(), request.paidAt(), request.tickets());
		String fingerprint = orderId + "|" + request.providerOrderId() + "|"
				+ request.actualAmountCents();
		ExternalPurchaseRecordRequest protectedRequest = request;
		return idempotency.execute("external-purchase-record", userId, key, fingerprint,
				() -> orders.recordExternalPurchase(orderId, protectedRequest));
	}

	@PostMapping("/orders/{orderId}/external-refund")
	public OrderResponse recordExternalRefund(@PathVariable String orderId,
			@RequestHeader("Authorization") String authorization,
			@RequestHeader(value = "Idempotency-Key", required = false) String key,
			@RequestBody ExternalRefundRecordRequest request) {
		String userId = principals.requireSubject(authorization);
		request = new ExternalRefundRecordRequest(userId, request.refundReference(),
				request.refundedAt());
		String fingerprint = orderId + "|" + request.refundReference() + "|"
				+ request.refundedAt();
		ExternalRefundRecordRequest protectedRequest = request;
		return idempotency.execute("external-refund-record", userId, key, fingerprint,
				() -> orders.recordExternalRefund(orderId, protectedRequest));
	}

	@PostMapping("/orders/{orderId}/cancel")
	public OrderResponse cancel(@PathVariable String orderId, @RequestHeader("Authorization") String authorization, @RequestHeader(value = "Idempotency-Key", required = false) String key,
			@RequestBody CancelOrderRequest request) {
		String userId = principals.requireSubject(authorization);
		request = new CancelOrderRequest(userId, request.reason());
		String fingerprint = orderId + "|" + request.reason();
		CancelOrderRequest protectedRequest = request;
		return idempotency.execute("order-cancel", userId, key, fingerprint, () -> orders.cancel(orderId, protectedRequest));
	}

	/** Endpoint for the payment gateway callback, not for a browser or WeChat client to call directly. */
	@PostMapping("/payments/wechat/notify")
	public OrderResponse paymentNotification(
			@RequestHeader(value = "Wechatpay-Signature", required = false) String signature,
			@RequestBody PaymentNotification notification) {
		return orders.paid(notification, signature);
	}
}
