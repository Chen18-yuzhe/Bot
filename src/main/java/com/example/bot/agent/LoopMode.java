package com.example.bot.agent;

/**
 * Agent Loop 的运行模式；每种任务类型选择一种模式，对应不同的循环与恢复策略。
 */
public enum LoopMode {
	/** 目标驱动：围绕目标反复 感知→推理→行动→观察→评估，直到给出最终回答。适合工作流、代码开发等一次性任务。 */
	GOAL,
	/** 定时驱动：到点唤醒后按 GOAL 模式执行；任务类型声明了重复周期时，完成后自动重排下一次。适合周报等延时任务。 */
	SCHEDULED,
	/** 监控驱动：周期性执行感知循环，模型输出结构化判定（TRIGGERED / CLEAR）；未触发则休眠到下一周期。适合订单退款通知等检测任务。 */
	MONITOR
}
